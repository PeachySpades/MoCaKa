// Cave Run: a long side-scrolling tunnel, generated fresh from a seed.
// It gets narrower and busier the further Moka gets.
window.makeRunLevel = function makeRunLevel(seed, length = 1200) {
  let s = seed >>> 0;
  const rand = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const pick = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));

  const H = 14;
  const cols = [];
  let top = 3, bot = 11;              // first open row, first floor row
  let nextMoth = 12, nextCrystal = 20, nextHazard = 26, nextOwl = 160, nextPillar = 40;
  const pillar = { left: 0, fromTop: false };
  const prev = { t: top, b: bot };

  for (let x = 0; x < length; x++) {
    const col = new Array(H).fill('#');
    const minGap = Math.max(3, 7 - Math.floor(x / 220));
    if (x > 14 && rand() < 0.4) {
      top = Math.max(1, Math.min(H - 1 - minGap, top + pick(-1, 1)));
      bot = Math.max(top + minGap, Math.min(H - 1, bot + pick(-1, 1)));
      if (bot - top > minGap + 4) bot--;
    }
    let t = top, b = bot;
    // pillars hang from the ceiling or rise from the floor, leaving a 2-tile squeeze
    if (pillar.left === 0 && x >= nextPillar && b - t >= 5) {
      pillar.left = pick(1, 2);
      pillar.fromTop = rand() < 0.5;
      nextPillar = x + pick(18, 34) - Math.min(10, Math.floor(x / 120));
    }
    if (pillar.left > 0) {
      if (pillar.fromTop) t = b - 2; else b = t + 2;
      pillar.left--;
    }
    // always overlap the previous column by 2 rows so the tunnel never seals
    if (t > prev.b - 2) t = prev.b - 2;
    if (b < prev.t + 2) b = prev.t + 2;
    prev.t = t; prev.b = b;
    for (let y = t; y < b; y++) col[y] = '.';

    const open = (y) => y >= t && y < b;
    if (x >= nextMoth) {
      col[pick(t, b - 1)] = 'm';
      nextMoth = x + pick(8, 14);
    } else if (x >= nextCrystal) {
      col[pick(t, b - 1)] = 'e';
      nextCrystal = x + pick(24, 34);
    } else if (x >= nextOwl && b - t >= 4) {
      col[Math.floor((t + b) / 2)] = 'o';
      nextOwl = x + pick(70, 110);
    } else if (x >= nextHazard && b - t >= 3) {
      // more bursting crystals the further you get
      const rv = rand(), crystalOdds = Math.min(0.4, 0.18 + x / 2500);
      const kind = rv < crystalOdds ? 'v' : rv < crystalOdds + 0.5 * (1 - crystalOdds) ? 's' : 'r';
      if (open(t)) col[t] = kind;
      nextHazard = x + Math.max(6, pick(14, 24) - Math.floor(x / 90));
    }
    cols.push(col);
  }
  // start and exit
  cols[4][7] = 'S';
  for (let x = 0; x < 12; x++) for (let y = 3; y < 11; y++) cols[x][y] = cols[x][y] === 'S' ? 'S' : '.';
  const last = cols[length - 3];
  const exitRow = last.findIndex((c) => c !== '#');
  last[exitRow >= 0 ? exitRow : 7] = 'E';

  const map = [];
  for (let y = 0; y < H; y++) map.push(cols.map((c) => c[y]).join(''));
  return { name: 'Cave Run', run: true, echoes: 8, map };
};

// Co-op Run: a finite side-scrolling cave for 1 to 4 bats, generated from a seed
// (the host sends it, so every device builds the same cave). Extra tiles:
//   K  checkpoint lantern     s  spider on the ceiling     c  cave crawler on the floor
//   o  owl                    g  a swarm of ghost moths
//   v  loose ceiling crystal (an echo cracks it and it bursts into flying pieces)
// It has four sections; monsters get denser and new kinds join in each one:
// spiders and crawlers first, then owls, then ghost moths. `difficulty` is
// 'easy', 'normal' or 'hard' and sets how close together the monsters are.
// `variant` ('classic', 'escape' or 'hunt'): Escape packs monsters tighter and
// brings owls and ghost moths in a section earlier; Hunt has a few more to smash.
// `map` 'explore' builds the big free-roaming Explore cave instead (makeCoopExplore below).
window.makeCoopLevel = function makeCoopLevel(seed, difficulty = 'normal', variant = 'classic', mapKind = 'scroll', stage = 0) {
  if (mapKind === 'explore') return window.makeCoopExplore(seed, difficulty, variant, stage);
  let s = seed >>> 0;
  const rand = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const pick = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));
  const spread = ({ easy: 1.45, normal: 1, hard: 0.74 }[difficulty] || 1) * ({ escape: 0.82, hunt: 0.9 }[variant] || 1);

  const H = 12, LEN = 400, SECTION = LEN / 4;
  const cps = [1, 2, 3].map((k) => Math.round(k * SECTION));
  const goalX = LEN - 7;
  const safe = (x) => x < 16 || x > LEN - 15 || cps.some((c) => Math.abs(x - c) <= 5);

  // pass 1: the tunnel's shape, as the first open row (top) and first floor row (bot) per column
  const T = [], B = [];
  let top = 3, bot = 9, tgtT = 2, tgtB = 10, nextChange = 0, nextPillar = 30;
  const pillar = { left: 0, fromTop: false };
  for (let x = 0; x < LEN; x++) {
    const section = Math.min(3, Math.floor(x / SECTION));
    if (safe(x)) { tgtT = 2; tgtB = 10; nextChange = x + 1; }
    else if (x >= nextChange) {
      if (rand() < 0.22) { tgtT = pick(1, 2); tgtB = pick(10, 11); }          // a roomy chamber
      else {
        const gap = pick(4, 7 - Math.min(2, section >> 1)), mid = pick(4, 7);
        tgtT = Math.max(1, Math.min(H - 1 - gap, mid - (gap >> 1)));
        tgtB = tgtT + gap;
      }
      nextChange = x + pick(7, 15);
    }
    if (top !== tgtT && rand() < 0.7) top += Math.sign(tgtT - top);
    if (bot !== tgtB && rand() < 0.7) bot += Math.sign(tgtB - bot);
    if (bot - top < 4) { if (top > 1) top--; else bot++; }
    let t = top, b = bot;
    // pillars from the ceiling or floor leave a 3-tile squeeze
    if (!safe(x) && pillar.left === 0 && x >= nextPillar && b - t >= 6) {
      pillar.left = pick(1, 2);
      pillar.fromTop = rand() < 0.5;
      nextPillar = x + pick(22, 38) - section * 3;
    }
    if (pillar.left > 0) {
      if (pillar.fromTop) t = b - 3; else b = t + 3;
      pillar.left--;
    }
    // always overlap the previous column by 3 rows, so a whole team fits through
    if (x > 0) {
      if (t > B[x - 1] - 3) t = B[x - 1] - 3;
      if (b < T[x - 1] + 3) b = T[x - 1] + 3;
    }
    T.push(Math.max(1, t)); B.push(Math.min(H - 1, b));
  }
  // the far end is closed off just past the goal
  for (let x = LEN - 2; x < LEN; x++) { T[x] = H; B[x] = H; }

  const cols = [];
  for (let x = 0; x < LEN; x++) {
    const col = new Array(H).fill('#');
    for (let y = T[x]; y < B[x]; y++) col[y] = '.';
    cols.push(col);
  }
  const midRow = (x) => Math.floor((T[x] + B[x]) / 2);
  const free = (x, y) => cols[x] && cols[x][y] === '.';

  // pass 2: pickups
  for (let x = 14; x < LEN - 6; x++) {
    if (rand() < 1 / 11) { const y = pick(T[x], B[x] - 1); if (free(x, y)) cols[x][y] = 'm'; }
  }
  for (let x = 20; x < LEN - 8; x += pick(17, 25)) {
    const y = pick(T[x], B[x] - 1);
    if (free(x, y)) cols[x][y] = 'e'; else if (free(x, midRow(x))) cols[x][midRow(x)] = 'e';
  }

  // pass 3: monsters, spaced by section and difficulty
  const kindsFor = (section) => (variant === 'escape'
    ? [['s', 'c', 'o'], ['s', 'c', 'o', 'g'], ['s', 'c', 'o', 'g'], ['s', 'c', 'o', 'g']]
    : [['s', 'c'], ['s', 'c', 'o'], ['s', 'c', 'o', 'g'], ['s', 'c', 'o', 'g']])[section];
  const fits = {
    // a spider needs a ceiling with room below to drop into
    s: (x) => B[x] - T[x] >= 4 && T[x - 1] === T[x] && free(x, T[x]) && T[x] > 0 ? [x, T[x]] : null,
    // a crawler needs a flat stretch of floor to pace along
    c: (x) => {
      for (let k = -1; k <= 1; k++) if (B[x + k] !== B[x]) return null;
      return B[x] - T[x] >= 4 && free(x, B[x] - 1) ? [x, B[x] - 1] : null;
    },
    o: (x) => B[x] - T[x] >= 5 && free(x, midRow(x) - 1) ? [x, midRow(x) - 1] : null,
    g: (x) => B[x] - T[x] >= 4 && free(x, midRow(x)) ? [x, midRow(x)] : null,
  };
  // the kind seen least so far goes first, so every section gets a good mix
  const used = { s: 0, c: 0, o: 0, g: 0 };
  let x = 24;
  while (x < LEN - 16) {
    const section = Math.min(3, Math.floor(x / SECTION));
    if (!safe(x)) {
      const kinds = kindsFor(section).map((k) => [k, used[k] + rand() * 1.5]).sort((a, b) => a[1] - b[1]).map((a) => a[0]);
      for (const k of kinds) {
        const at = fits[k](x) || fits[k](x + 1) || fits[k](x + 2);
        if (at) { cols[at[0]][at[1]] = k; used[k]++; break; }
      }
    }
    x += Math.max(4, Math.round([15, 12, 10, 8.5][section] * spread * (0.75 + rand() * 0.5)));
  }

  // pass 4: loose ceiling crystals ('v') that burst when an echo reaches them. Closer
  // together in each section and on harder levels; never near the start, a lantern or the goal,
  // and never right beside a spider. (Placed last, so the rest of the cave is the same as before.)
  const shardGap = [24, 19, 15, 12], shardK = ({ easy: 1.4, normal: 1, hard: 0.78 }[difficulty] || 1) * ({ escape: 0.85, hunt: 0.95 }[variant] || 1);
  const nearSpider = (x) => [-1, 0, 1].some((k) => cols[x + k] && cols[x + k].includes('s'));
  for (let x2 = 30; x2 < LEN - 18;) {
    const section = Math.min(3, Math.floor(x2 / SECTION));
    let put = false;
    for (let k = 0; k < 4 && !put; k++) {
      const xx = x2 + k;
      if (safe(xx) || cps.some((c) => Math.abs(xx - c) <= 6) || nearSpider(xx)) continue;
      const y = T[xx];
      if (y < 1 || B[xx] - y < 4 || !free(xx, y) || !free(xx, y + 1)) continue;
      cols[xx][y] = 'v'; put = true;
    }
    x2 += Math.max(5, Math.round(shardGap[section] * shardK * (0.7 + rand() * 0.6)));
  }

  // start, checkpoints and the goal
  for (let x2 = 0; x2 < 12; x2++) for (let y = T[x2]; y < B[x2]; y++) cols[x2][y] = '.';
  cols[5][6] = 'S';
  for (const c of cps) cols[c][Math.min(B[c] - 1, Math.max(T[c], 6))] = 'K';
  cols[goalX][midRow(goalX)] = 'E';

  const map = [];
  for (let y = 0; y < H; y++) map.push(cols.map((c) => c[y]).join(''));
  return { name: 'Co-op Run', coop: true, echoes: 8, seed: seed >>> 0, difficulty, variant, map };
};

// Co-op Explore: a big cave the team roams freely, no scrolling. Generated from the seed
// (so host and guests build the same one), same tiles as the Co-op Run. A grid of
// chambers joined by wide winding tunnels in every direction (a random spanning tree,
// plus a few loops), so there are side branches and dead ends with moths in them.
// The start is in the leftmost column of chambers; the exit (a big cave mouth out to the
// night sky) is in whichever chamber of the three rightmost columns is the longest flight
// away, so the way winds; lanterns sit along the way between them, in order. Monsters get
// denser, and new kinds join in, the closer they are to the exit (the same four "sections").
//
// Classic and Escape fly a run of three caves (`stage` 0, 1, 2: crystal, lava, ice, see
// COOP_STAGES); Hunt is one crystal cave. Each cave also has, in the hard-to-reach spots:
//   k  a key (stage + 1 of them; the exit stays locked until the team has them all; none in Hunt)
//   h  a heart (the team keeps them to revive fallen bats)
//   p  a power-up (its type in def.powers['x,y'])
//   G  a gate: solid rock until its switch (w) is hit. def.gates: [{ tiles: [[x, y]...], sw: [x, y] }]
// Hard-to-reach means: dead-end chambers (the farthest from the way through first), pockets
// sealed off by a gate, and little nooks at the end of a one-tile-wide crawl into the rock.
window.COOP_STAGES = [
  { name: 'Crystal Cave', arena: 0 },
  { name: 'Lava Cave', arena: 1 },
  { name: 'Ice Cave', arena: 3 },
];
window.COOP_POWERS = ['speed', 'shield', 'fire', 'freeze', 'ghost', 'mega', 'frenzy'];
window.makeCoopExplore = function makeCoopExplore(seed, difficulty = 'normal', variant = 'classic', stage = 0) {
  stage = Math.max(0, Math.min(2, stage | 0));
  let s = (seed ^ 0x5eed ^ Math.imul(stage, 0x9e3779b1)) >>> 0;
  const rand = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const pick = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));
  const spread = ({ easy: 1.4, normal: 1, hard: 0.78 }[difficulty] || 1) * ({ escape: 0.85, hunt: 0.88 }[variant] || 1);
  // a run of three caves keeps each one a little smaller (10 x 5 chambers, 122 x 52 tiles)
  const run = variant !== 'hunt';
  const CW = 12, CH = 10, NX = run ? 10 : 12, NY = 5;
  const W = NX * CW + 2, H = NY * CH + 2;
  const g = [];
  for (let y = 0; y < H; y++) g.push(new Array(W).fill('#'));
  // (a closed gate counts as rock)
  const open = (x, y) => x > 0 && y > 0 && x < W - 1 && y < H - 1 && g[y][x] !== '#' && g[y][x] !== 'G';
  const rock = (x, y) => x <= 0 || y <= 0 || x >= W - 1 || y >= H - 1 || g[y][x] === '#';
  const carve = (x, y) => { if (x > 0 && y > 0 && x < W - 1 && y < H - 1) g[y][x] = '.'; };
  const disk = (cx, cy, r) => {
    for (let y = Math.floor(cy - r); y <= Math.ceil(cy + r); y++) {
      for (let x = Math.floor(cx - r); x <= Math.ceil(cx + r); x++) if ((x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= r * r) carve(x, y);
    }
  };

  // chambers: one per cell, roomy or just a small junction
  const sj = pick(1, NY - 2);
  const cells = [];
  for (let j = 0; j < NY; j++) {
    for (let i = 0; i < NX; i++) {
      const ends = i === 0 && j === sj;
      const small = !ends && rand() < 0.28;
      cells.push({
        i, j, cx: 1 + i * CW + CW / 2 + pick(-2, 2), cy: 1 + j * CH + CH / 2 + pick(-1, 1),
        rw: ends ? 4 : small ? pick(1, 2) : pick(2, 4), rh: ends ? 3 : small ? pick(1, 2) : pick(2, 3),
      });
    }
  }
  const cell = (i, j) => cells[j * NX + i];
  // a random spanning tree over the grid (Kruskal), then a few extra links for loops
  const parent = cells.map((_, k) => k);
  const find = (k) => (parent[k] === k ? k : (parent[k] = find(parent[k])));
  const edges = [];
  for (let j = 0; j < NY; j++) for (let i = 0; i < NX; i++) {
    if (i < NX - 1) edges.push([j * NX + i, j * NX + i + 1, rand()]);
    if (j < NY - 1) edges.push([j * NX + i, (j + 1) * NX + i, rand() * 0.9]);
  }
  edges.sort((a, b) => a[2] - b[2]);
  const links = [];
  for (const e of edges) {
    const a = find(e[0]), b = find(e[1]);
    if (a !== b) { parent[a] = b; links.push(e); } else if (rand() < 0.12) links.push(e);
  }
  for (const c of cells) {
    // an organic blob: a few overlapping disks
    const n = 2 + Math.floor((c.rw + c.rh) / 2);
    for (let k = 0; k < n; k++) {
      const r = Math.min(c.rw, c.rh) + 0.4 + rand() * 0.8;
      disk(c.cx + (rand() * 2 - 1) * (c.rw - r * 0.6 + 0.5), c.cy + (rand() * 2 - 1) * Math.max(0, c.rh - r * 0.6), r);
    }
    disk(c.cx, c.cy, 1.6);
  }
  // tunnels: wobbly, always at least 3 tiles wide so a whole team fits
  for (const [a, b] of links) {
    const A = cells[a], B = cells[b], len = Math.hypot(B.cx - A.cx, B.cy - A.cy);
    const nx = -(B.cy - A.cy) / len, ny = (B.cx - A.cx) / len, amp = rand() * 2.2, ph = rand() * 6.28, r = 1.55 + rand() * 0.4;
    for (let t = 0; t <= 1; t += 0.4 / len) {
      const w = Math.sin(t * Math.PI) * Math.sin(t * Math.PI * 2 + ph) * amp;
      disk(A.cx + (B.cx - A.cx) * t + nx * w, A.cy + (B.cy - A.cy) * t + ny * w, r);
    }
  }

  // distance (in tiles flown) from some tiles to every open tile
  const flood = (...from) => {
    const d = new Int32Array(W * H).fill(-1), q = [];
    for (const [fx, fy] of from) { d[fy * W + fx] = 0; q.push(fy * W + fx); }
    for (let h = 0; h < q.length; h++) {
      const k = q[h], x = k % W, y = (k - x) / W;
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        const nk = (y + dy) * W + x + dx;
        if (d[nk] < 0 && open(x + dx, y + dy)) { d[nk] = d[k] + 1; q.push(nk); }
      }
    }
    return d;
  };
  // start, and the exit: the farthest chamber (by flying) in the three rightmost columns.
  // The exit chamber is roomy: the big cave mouth opens in its back wall.
  const S = cell(0, sj);
  const sx = Math.floor(S.cx), sy = Math.floor(S.cy);
  disk(sx + 0.5, sy + 0.5, 3.2);
  const fromStart = flood([sx, sy]);
  let E = cell(NX - 1, 0);
  for (const c of cells) if (c.i >= NX - 3 && fromStart[Math.floor(c.cy) * W + Math.floor(c.cx)] > fromStart[Math.floor(E.cy) * W + Math.floor(E.cx)]) E = c;
  const ex = Math.floor(E.cx), ey = Math.floor(E.cy);
  disk(ex + 0.5, ey + 0.5, 3.1);
  const dist = flood([ex, ey]);
  const total = dist[sy * W + sx];
  const D = (x, y) => (open(x, y) ? dist[y * W + x] : -1);
  // the way from the start to the exit, for the lanterns
  const route = [[sx, sy]];
  for (let x = sx, y = sy; D(x, y) > 0;) {
    const here = D(x, y);
    const nxt = [[1, 0], [-1, 0], [0, 1], [0, -1]].map(([dx, dy]) => [x + dx, y + dy]).find(([a, b]) => D(a, b) === here - 1);
    [x, y] = nxt; route.push([x, y]);
  }
  const lanterns = [];
  for (const f of run ? [0.34, 0.67] : [0.27, 0.52, 0.76]) {
    let [x, y] = route[Math.round(f * (route.length - 1))];
    // a little way down toward the floor, but still on the way through
    for (let k = 0; k < 2 && open(x, y + 1) && open(x, y + 2); k++) y++;
    lanterns.push([x, y]);
  }
  // how far along a tile is: 0 at the start, 1 at the exit (by flying distance)
  const along = (x, y) => Math.max(0, Math.min(1, 1 - D(x, y) / total));
  const section = (x, y) => Math.min(3, Math.floor(along(x, y) * 4));
  const near = (x, y, pts, r) => pts.some(([a, b]) => Math.hypot(a - x, b - y) < r);
  const safe = (x, y) => Math.hypot(x - sx, y - sy) < 9 || Math.hypot(x - ex, y - ey) < 6 || near(x, y, lanterns, 5);
  const free = (x, y) => open(x, y) && g[y][x] === '.';
  const openBelow = (x, y) => { let n = 0; while (open(x, y + n + 1)) n++; return n; };
  const roomy = (x, y, r) => { for (let b = y - r; b <= y + r; b++) for (let a = x - r; a <= x + r; a++) if (!open(a, b)) return false; return true; };
  const deg = cells.map(() => 0);
  for (const [a, b] of links) { deg[a]++; deg[b]++; }
  const openTiles = [];
  for (let y = 1; y < H - 1; y++) for (let x = 1; x < W - 1; x++) if (open(x, y) && D(x, y) >= 0) openTiles.push([x, y]);
  const any = () => openTiles[Math.floor(rand() * openTiles.length)];

  // ---- keys, switch gates, power-ups and hearts, in the hard-to-reach spots ----
  const routeSet = new Set(route.map(([x, y]) => y * W + x));
  const fromRoute = flood(...route);
  const items = [], gates = [], gateTiles = [], powers = {};
  const inPocket = new Uint8Array(W * H);   // 1 + the gate's index, for tiles sealed behind a gate
  const place = (x, y, ch, type) => { g[y][x] = ch; items.push([x, y]); if (type) powers[`${x},${y}`] = type; };
  // dead-end chambers (one tunnel in), the farthest from the way through first
  const leaves = cells.filter((c, k) => deg[k] === 1 && c !== S && c !== E && free(Math.floor(c.cx), Math.floor(c.cy)))
    .sort((a, b) => fromRoute[Math.floor(b.cy) * W + Math.floor(b.cx)] - fromRoute[Math.floor(a.cy) * W + Math.floor(a.cx)]);
  // seal a dead end with a gate across its tunnel, and put its switch somewhere outside.
  // The gate is every tile exactly t steps from the chamber's middle: any way out has to cross it.
  const reach = () => { const d = flood([sx, sy]); let n = 0; for (let k = 0; k < W * H; k++) if (d[k] >= 0) n++; return n; };
  // a side cavern for a switch: a crawl from a tunnel into the rock, a turn, a second leg and a
  // small den at the end with the lever on its floor. It only touches the cave at its mouth (a
  // dead end nobody flies through, so never on the way to anything), round a corner (it can't be
  // seen from the tunnel), its mouth off the way through, outside every pocket and a short flight
  // (d: steps from the pocket's middle, t: the gate's) from the gate. Roomiest shape that fits.
  // nothing else open within gap tiles of a lever at sw (dug: the den's own tiles), and no clear
  // line of sight to it from anywhere in the cave outside its den
  function hidden([wx, wy], dug, gap) {
    const cx = wx + 0.5, cy = wy + 0.5;
    for (let y = Math.max(1, wy - 14); y <= Math.min(H - 2, wy + 14); y++) {
      for (let x = Math.max(1, wx - 14); x <= Math.min(W - 2, wx + 14); x++) {
        if (rock(x, y) || dug.has(y * W + x)) continue;
        const dd = Math.hypot(x - wx, y - wy);
        if (dd < gap) return false;
        if (dd > 14) continue;
        let seen = true;
        for (let i = 1, n = Math.ceil(dd * 4); i < n && seen; i++) {
          const f = i / n, qx = Math.floor(x + 0.5 + (cx - x - 0.5) * f), qy = Math.floor(y + 0.5 + (cy - y - 0.5) * f);
          if (rock(qx, qy) && !dug.has(qy * W + qx)) seen = false;
        }
        if (seen) return false;
      }
    }
    return true;
  }
  function switchDen(d, t) {
    const dirs = [[1, 0], [-1, 0], [0, 1], [0, -1]];
    // [leg width, first leg, second leg, den across, den deep]
    const SHAPES = [[2, 3, 3, 4, 3], [2, 3, 2, 4, 3], [2, 3, 2, 3, 3], [1, 3, 2, 3, 3], [1, 2, 2, 3, 2], [1, 2, 1, 2, 2]];
    const tiers = [[], [], []];
    for (let k = 0; k < W * H; k++) {
      if (d[k] < t + 3 || d[k] > t + 26 || inPocket[k]) continue;
      const x = k % W, y = (k - x) / W;
      if (g[y][x] !== '.' || safe(x, y) || near(x, y, items, 4) || near(x, y, gateTiles, 4)) continue;
      tiers[routeSet.has(k) ? 2 : fromRoute[k] >= 2 && d[k] <= t + 18 ? 0 : 1].push([x, y]);
    }
    for (const list of tiers) for (let i = list.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [list[i], list[j]] = [list[j], list[i]]; }
    // (the lever wants rock between it and the rest of the cave: gap tiles, then a little less)
    for (const gap of [3.2, 2.2]) for (const list of tiers) {
      for (const [lw, a, b, dw, dd] of SHAPES) {
        for (const [x, y] of list) {
          const o0 = Math.floor(rand() * 8);
          for (let o = 0; o < 8; o++) {
            const [dx, dy] = dirs[(o0 + o) % 8 >> 1], side = (o0 + o) % 2 ? 1 : -1, px = -dy * side, py = dx * side;
            if (!rock(x + dx, y + dy)) continue;
            const own = new Map();   // local (u along the crawl, v to the side) for each dug tile
            const add = (u, v) => own.set(u * 64 + v, [u, v]);
            for (let u = 1; u <= a; u++) for (let v = 0; v < lw; v++) add(u, v);                          // first leg
            for (let v = lw; v < lw + b; v++) for (let u = a - lw + 1; u <= a; u++) add(u, v);             // round the corner
            for (let v = lw + b; v < lw + b + dd; v++) for (let u = a - lw + 1; u <= a - lw + dw; u++) add(u, v);   // the den
            const at = (u, v) => [x + dx * u + px * v, y + dy * u + py * v];
            let ok = true;
            for (const [u, v] of own.values()) {
              const [tx, ty] = at(u, v);
              if (tx < 2 || ty < 2 || tx > W - 3 || ty > H - 3) { ok = false; break; }
              for (let dv = -1; dv <= 1 && ok; dv++) for (let du = -1; du <= 1 && ok; du++) {
                const nu = u + du, nv = v + dv;
                if (own.has(nu * 64 + nv) || (u === 1 && v < lw && nu <= 0)) continue;   // its own tiles, or the mouth
                if (!rock(...at(nu, nv))) ok = false;
              }
              if (!ok) break;
            }
            if (!ok) continue;
            // the lever: on the den's floor (rock below it, room above), as deep in as it goes
            const dug = new Set([...own.values()].map(([u, v]) => { const [tx, ty] = at(u, v); return ty * W + tx; }));
            let sw = null, sd = -1;
            for (const [u, v] of own.values()) {
              if (v < lw + b) continue;
              const [tx, ty] = at(u, v), deep = v * 4 + u;
              const floor = !dug.has((ty + 1) * W + tx), roof = dug.has((ty - 1) * W + tx);
              if (floor && roof && deep > sd) { sd = deep; sw = [tx, ty]; }
            }
            if (!sw || !hidden(sw, dug, gap)) continue;
            for (const [u, v] of own.values()) carve(...at(u, v));
            return sw;
          }
        }
      }
    }
    return null;
  }
  function makeGate(c) {
    const cx = Math.floor(c.cx), cy = Math.floor(c.cy), d = flood([cx, cy]);
    let best = null;
    for (let t = Math.max(c.rw, c.rh) + 2; t <= 13; t++) {
      const ring = [];
      for (let k = 0; k < W * H && ring.length <= 7; k++) if (d[k] === t) ring.push(k);
      if (ring.length < 2 || ring.length > 7) continue;
      const mx = ring.reduce((a, k) => a + (k % W), 0) / ring.length, my = ring.reduce((a, k) => a + Math.floor(k / W), 0) / ring.length;
      if (ring.some((k) => Math.hypot((k % W) - mx, Math.floor(k / W) - my) > 3.6)) continue;
      // nothing that matters behind it: the way through, a lantern, another pocket
      let inner = 0, clash = false;
      for (let k = 0; k < W * H; k++) if (d[k] >= 0 && d[k] <= t) { if (d[k] < t) inner++; if (routeSet.has(k) || inPocket[k] || g[Math.floor(k / W)][k % W] !== '.') clash = true; }
      if (clash || inner < 14) continue;
      // and it only shuts off the pocket: the rest of the cave stays reachable from the start
      const before = reach();
      for (const k of ring) g[Math.floor(k / W)][k % W] = 'G';
      const after = reach();
      for (const k of ring) g[Math.floor(k / W)][k % W] = '.';
      if (before - after !== inner + ring.length) continue;
      if (!best || ring.length < best.ring.length) best = { t, ring };
    }
    if (!best) return null;
    // the switch: in its own little side cavern a short flight from the gate, dug into the rock
    // off a tunnel (never on the way through) and round a corner, so it isn't seen at a glance
    const sw = switchDen(d, best.t);
    if (!sw) return null;
    const id = gates.length;
    for (let k = 0; k < W * H; k++) if (d[k] >= 0 && d[k] < best.t) inPocket[k] = id + 1;
    const tiles = best.ring.map((k) => [k % W, Math.floor(k / W)]);
    for (const [x, y] of tiles) { g[y][x] = 'G'; gateTiles.push([x, y]); }
    g[sw[1]][sw[0]] = 'w'; items.push(sw);
    gates.push({ tiles, sw });
    return { id, x: cx, y: cy };
  }
  // a little nook at the end of a one-tile-wide crawl into the rock (it never breaks into another cave)
  function makeNook() {
    for (let tries = 0; tries < 400; tries++) {
      const [x, y] = any();
      if (safe(x, y) || inPocket[y * W + x] || g[y][x] !== '.' || near(x, y, items, 6)) continue;
      const [dx, dy] = [[1, 0], [-1, 0], [0, 1], [0, -1]][Math.floor(rand() * 4)], px = -dy, py = dx;
      if (!rock(x + dx, y + dy)) continue;
      const n = pick(3, 5), path = [], nook = [];
      for (let i = 1; i <= n; i++) path.push([x + dx * i, y + dy * i]);
      for (let i = n + 1; i <= n + 2; i++) for (let j = -1; j <= 1; j++) nook.push([x + dx * i + px * j, y + dy * i + py * j]);
      const mine = new Set([...path, ...nook].map(([a, b]) => b * W + a));
      let ok = true;
      for (const [a, b] of [...path.slice(1), ...nook]) {
        if (a < 2 || b < 2 || a > W - 3 || b > H - 3) { ok = false; break; }
        for (let v = -1; v <= 1 && ok; v++) for (let u = -1; u <= 1 && ok; u++) {
          const qa = a + u, qb = b + v;
          if (!mine.has(qb * W + qa) && !rock(qa, qb)) ok = false;
        }
        if (!ok) break;
      }
      if (!ok) continue;
      for (const [a, b] of [...path, ...nook]) carve(a, b);
      return [x + dx * (n + 2), y + dy * (n + 2)];
    }
    return null;
  }
  const spare = [];
  const leafSpot = () => {
    const c = spare.shift() || leaves.shift();
    return c ? [Math.floor(c.cx), Math.floor(c.cy)] : null;
  };
  // somewhere well off the way through, if the dead ends and nooks run out
  const farSpot = () => {
    for (let tries = 0; tries < 2000; tries++) {
      const [x, y] = any();
      if (!safe(x, y) && free(x, y) && !inPocket[y * W + x] && fromRoute[y * W + x] >= 5 - tries / 600 && !near(x, y, items, 5)) return [x, y];
    }
    return null;
  };
  // a second thing in a pocket goes a little way from the first
  const besideIn = (pk) => {
    for (let r = 1.5; r < 4; r += 0.5) {
      for (let k = 0; k < 40; k++) {
        const x = pk.x + pick(-3, 3), y = pk.y + pick(-2, 2);
        if (free(x, y) && inPocket[y * W + x] === pk.id + 1 && !near(x, y, items, r)) return [x, y];
      }
    }
    return null;
  };
  const K = run ? stage + 1 : 0;
  const pockets = [];
  for (let want = run ? [1, 2, 2][stage] : 1; pockets.length < want && leaves.length;) {
    const c = leaves.shift(), pk = makeGate(c);
    if (pk) pockets.push(pk); else spare.push(c);
  }
  const POOL = window.COOP_POWERS;
  const powerType = () => POOL[Math.floor(rand() * POOL.length)];
  const putAt = (spot, ch, type) => { if (spot) place(spot[0], spot[1], ch, type); return !!spot; };
  // the first pocket hides a key (Hunt: a power-up) and a heart; the second a power-up and a heart
  if (pockets[0]) { putAt([pockets[0].x, pockets[0].y], K ? 'k' : 'p', K ? null : powerType()); putAt(besideIn(pockets[0]), 'h'); }
  if (pockets[1]) { putAt([pockets[1].x, pockets[1].y], 'p', powerType()); putAt(besideIn(pockets[1]), 'h'); }
  // the other keys: the farthest dead ends, then nooks
  for (let n = K - (pockets[0] ? 1 : 0); n > 0; n--) putAt(leafSpot() || makeNook() || farSpot(), 'k');
  // power-ups: a nook, then dead ends
  putAt(makeNook() || leafSpot() || farSpot(), 'p', powerType());
  putAt(leafSpot() || makeNook() || farSpot(), 'p', powerType());
  if (!pockets[1]) putAt(makeNook() || leafSpot() || farSpot(), 'p', powerType());
  // hearts: a nook, a dead end, and one more tucked away
  putAt(makeNook() || leafSpot() || farSpot(), 'h');
  putAt(leafSpot() || farSpot(), 'h');
  if (!pockets[0]) putAt(farSpot(), 'h');

  // moths: extra ones tucked in dead-end chambers, the rest scattered
  cells.forEach((c, k) => {
    if (deg[k] !== 1 || c === S || c === E) return;
    for (let n = pick(2, 3), tries = 0; n > 0 && tries < 20; tries++) {
      const x = Math.floor(c.cx) + pick(-2, 2), y = Math.floor(c.cy) + pick(-1, 1);
      if (free(x, y) && !near(x, y, items, 1.5)) { g[y][x] = 'm'; n--; }
    }
  });
  for (let n = Math.round(openTiles.length / 110); n > 0;) { const [x, y] = any(); if (free(x, y) && !near(x, y, [[sx, sy]], 3)) { g[y][x] = 'm'; n--; } }
  for (let n = Math.round(openTiles.length / 150); n > 0;) { const [x, y] = any(); if (free(x, y) && !near(x, y, [[sx, sy]], 3)) { g[y][x] = 'e'; n--; } }

  // monsters, spaced out (closer together toward the exit and on harder levels)
  const kindsFor = (sec) => (variant === 'escape'
    ? [['s', 'c', 'o'], ['s', 'c', 'o', 'g'], ['s', 'c', 'o', 'g'], ['s', 'c', 'o', 'g']]
    : [['s', 'c'], ['s', 'c', 'o'], ['s', 'c', 'o', 'g'], ['s', 'c', 'o', 'g']])[sec];
  const fits = {
    // a spider hangs from a ceiling with 4 to 8 tiles of air below to drop into
    s: (x, y) => rock(x, y - 1) && free(x, y) && openBelow(x, y) >= 4 && openBelow(x, y) <= 8,
    // a crawler paces a flat stretch of floor
    c: (x, y) => free(x, y) && rock(x, y + 1) && rock(x - 1, y + 1) && rock(x + 1, y + 1) && open(x - 1, y) && open(x + 1, y) && open(x, y - 1) && open(x, y - 2),
    // an owl perches in open air with room to swoop
    o: (x, y) => free(x, y) && roomy(x, y, 1) && open(x - 2, y) && open(x + 2, y) && open(x, y - 2) && open(x, y + 2),
    g: (x, y) => free(x, y) && roomy(x, y, 1),
  };
  const used = { s: 0, c: 0, o: 0, g: 0 }, placed = [];
  const gap = [12, 10, 8.5, 7.5];
  // (stage by stage the caves get a little busier)
  const busy = 1 - stage * 0.06;
  for (let tries = 0; tries < 5000; tries++) {
    let [x, y] = any();
    if (safe(x, y)) continue;
    const sec = section(x, y), want = gap[sec] * spread * busy;
    if (near(x, y, placed, want)) continue;
    const kinds = kindsFor(sec).map((k) => [k, used[k] + rand() * 1.5]).sort((a, b) => a[1] - b[1]).map((a) => a[0]);
    for (const k of kinds) {
      // spiders look up for a ceiling, crawlers down for a floor
      let px = x, py = y;
      if (k === 's') while (open(px, py - 1)) py--;
      if (k === 'c') while (open(px, py + 1)) py++;
      if (!fits[k](px, py) || safe(px, py) || near(px, py, placed, want) || near(px, py, items, 2.5) || near(px, py, gateTiles, 2.5)) continue;
      g[py][px] = k; used[k]++; placed.push([px, py]);
      break;
    }
  }

  // loose ceiling crystals, never near the start, a lantern, the exit, a gate or right beside a spider
  const shardGap = [20, 16, 13, 11], shardK = ({ easy: 1.4, normal: 1, hard: 0.78 }[difficulty] || 1) * ({ escape: 0.85, hunt: 0.95 }[variant] || 1);
  const shards = [];
  for (let tries = 0; tries < 4000; tries++) {
    let [x, y] = any();
    while (open(x, y - 1)) y--;
    if (safe(x, y) || !free(x, y) || !free(x, y + 1) || openBelow(x, y) < 3 || !rock(x, y - 1)) continue;
    if (near(x, y, shards, shardGap[section(x, y)] * shardK) || near(x, y, gateTiles, 2) || [-1, 0, 1].some((k) => g[y][x + k] === 's')) continue;
    g[y][x] = 'v'; shards.push([x, y]);
  }

  g[sy][sx] = 'S';
  g[ey][ex] = 'E';
  for (const [x, y] of lanterns) g[y][x] = 'K';
  const st = window.COOP_STAGES[stage];
  return {
    name: 'Co-op Explore', coop: true, explore: true, map: g.map((r) => r.join('')), echoes: 8,
    seed: seed >>> 0, difficulty, variant, mapKind: 'explore',
    stage, stages: run ? 3 : 1, stageName: st.name, arena: st.arena, keys: K, gates, powers,
  };
};
